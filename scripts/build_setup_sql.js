/**
 * Rebuilds backend/migrations/setup_all.sql — every migration concatenated in
 * order, so a fresh or lagging Supabase project can be brought up to date with
 * one paste into the SQL Editor.
 *
 *   node scripts/build_setup_sql.js
 *
 * 002 is skipped: 007 supersedes it and nothing reads its `test_type` column.
 */
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const migDir = path.join(root, 'backend/migrations');
const sources = [
  ...fs
    .readdirSync(migDir)
    .filter((f) => /^\d{3}_.+\.sql$/.test(f) && !f.startsWith('002_'))
    .sort()
    .map((f) => `backend/migrations/${f}`),
  'exam/backend/schema.sql',
  'exam/backend/migrations/001_exam_hardening.sql',
];

const header = `-- ============================================================================
--  IQ — ONE-SHOT DATABASE SETUP (generated by scripts/build_setup_sql.js)
--
--  HOW TO RUN
--    Supabase Dashboard -> SQL Editor -> New query -> paste this whole file -> Run.
--    Every section is idempotent, so it is safe on a fresh project and on the
--    live one, and safe to run again.
--
--  WHAT IT IS
--    ${sources.join('\n--    ')}
--    concatenated in order. Those files are the source of truth; edit them and
--    re-run the generator rather than editing this file.
-- ============================================================================
`;

const footer = `

-- ############################################################################
-- ##  Make PostgREST see the new tables/columns immediately
-- ############################################################################
notify pgrst, 'reload schema';

-- Quick check — every row should say true.
select 'tests.paper_pattern' as item, exists (select 1 from information_schema.columns where table_schema='public' and table_name='tests' and column_name='paper_pattern') as ok
union all select 'tests.results_published', exists (select 1 from information_schema.columns where table_schema='public' and table_name='tests' and column_name='results_published')
union all select 'answers.status',          exists (select 1 from information_schema.columns where table_schema='public' and table_name='answers' and column_name='status')
union all select 'srs.due_at',              exists (select 1 from information_schema.columns where table_schema='public' and table_name='spaced_repetition_state' and column_name='due_at')
union all select 'answers unique key',      exists (select 1 from pg_constraint where conname='answers_attempt_question_unique')
union all select 'attempts unique key',     exists (select 1 from pg_constraint where conname='attempts_student_test_unique')
union all select 'attempt_violations',      to_regclass('public.attempt_violations') is not null
union all select 'exam_sessions',           to_regclass('public.exam_sessions') is not null
union all select 'is_staff()',              to_regprocedure('public.is_staff()') is not null;
`;

let out = header;
for (const rel of sources) {
  out += `\n\n-- ############################################################################\n-- ##  ${rel}\n-- ############################################################################\n\n`;
  out += fs.readFileSync(path.join(root, rel), 'utf8');
}
out += footer;
fs.writeFileSync(path.join(migDir, 'setup_all.sql'), out.replace(/\r\n/g, '\n'));
console.log(`setup_all.sql written from ${sources.length} files`);
